"""Build scripts/i18n/lang_<code>.gd from tools/i18n/<code>_*.txt (tab-separated: Korean source<TAB>
translation; "source|context" for the same Korean word with another meaning). Keys are written exactly
as they appear in the GDScript source (escapes such as \\n kept), so the runtime strings match.
English must cover every Korean string (CI); other languages (ja) fall back to English where a line
is missing.
--check: change nothing; fail if a table is stale or a string has no English (run in CI)."""
import glob
import subprocess
import sys

LANGS = {"en": "LangEN", "ja": "LangJA"}
NAMES = {"en": "English", "ja": "Japanese"}


def q(s):
    return '"' + s.replace('"', '\\"') + '"'


def build(code):
    rows = {}
    ctxs = {}  # context -> {source: translation} (same Korean word, different meaning)
    for f in sorted(glob.glob("tools/i18n/%s_*.txt" % code)):
        for ln, line in enumerate(open(f, encoding="utf-8"), 1):
            line = line.rstrip("\n")
            if not line.strip() or line.startswith("#"):
                continue
            if "\t" not in line:
                sys.exit("%s:%d missing tab" % (f, ln))
            k, v = line.split("\t", 1)
            if "|" in k:
                k, ctx = k.split("|", 1)
                ctxs.setdefault(ctx, {})[k] = v
            else:
                rows[k] = v
    out = ["class_name %s" % LANGS[code], "## %s strings keyed by the Korean source text." % NAMES[code],
           "## Generated by tools/i18n_build.py from tools/i18n/%s_*.txt - edit those, not this file." % code, "const T := {"]
    for k in sorted(rows):
        out.append("\t%s: %s," % (q(k), q(rows[k])))
    out.append("}")
    out.append("const C := {")
    for c in sorted(ctxs):
        out.append("\t%s: {%s}," % (q(c), ", ".join("%s: %s" % (q(k), q(v)) for k, v in sorted(ctxs[c].items()))))
    out.append("}")
    return rows, "\n".join(out) + "\n"


tables = {c: build(c) for c in LANGS}
if "--check" in sys.argv:
    # CI: the generated tables must match their sources (a hand edit there is lost on the next
    # build) and every Korean string in the code must have an English line
    for c, (rows, text) in tables.items():
        if open("scripts/i18n/lang_%s.gd" % c, encoding="utf-8").read() != text:
            sys.exit("scripts/i18n/lang_%s.gd differs from tools/i18n/%s_*.txt: add the strings there and run tools/i18n_build.py" % (c, c))
    sys.exit(subprocess.run([sys.executable, "tools/i18n_extract.py", "--missing", "--strict"]).returncode)
for c, (rows, text) in tables.items():
    open("scripts/i18n/lang_%s.gd" % c, "w", encoding="utf-8").write(text)
    print("wrote", len(rows), NAMES[c], "strings")
subprocess.run([sys.executable, "tools/i18n_extract.py", "--missing"])
subprocess.run([sys.executable, "tools/i18n_extract.py", "--missing-lang", "ja"])
