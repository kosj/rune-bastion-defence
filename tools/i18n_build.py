"""Build scripts/i18n/lang_en.gd from tools/i18n/en_*.txt (tab-separated: Korean source<TAB>English).
Keys are written exactly as they appear in the GDScript source (escapes such as \\n kept), so the
runtime strings match. Reports source strings that have no translation yet."""
import glob
import json
import subprocess
import sys

rows = {}
ctxs = {}  # context -> {source: translation} (same Korean word, different meaning)
for f in sorted(glob.glob("tools/i18n/en_*.txt")):
    for ln, line in enumerate(open(f, encoding="utf-8"), 1):
        line = line.rstrip("\n")
        if not line.strip() or line.startswith("#"):
            continue
        if "\t" not in line:
            sys.exit("%s:%d missing tab" % (f, ln))
        k, v = line.split("\t", 1)
        if "|" in k:
            k, ctx = k.split("|", 1)
            ctxs.setdefault(ctx, {})[k] = v
        else:
            rows[k] = v


def q(s):
    return '"' + s.replace('"', '\\"') + '"'


out = ["class_name LangEN", "## English strings keyed by the Korean source text.",
       "## Generated by tools/i18n_build.py from tools/i18n/en_*.txt - edit those, not this file.", "const T := {"]
for k in sorted(rows):
    out.append("\t%s: %s," % (q(k), q(rows[k])))
out.append("}")
out.append("const C := {")
for c in sorted(ctxs):
    out.append("\t%s: {%s}," % (q(c), ", ".join("%s: %s" % (q(k), q(v)) for k, v in sorted(ctxs[c].items()))))
out.append("}")
open("scripts/i18n/lang_en.gd", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote", len(rows), "strings")
subprocess.run([sys.executable, "tools/i18n_extract.py", "--missing"])
